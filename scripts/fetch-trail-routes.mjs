// Regenerates src/lib/trailRoutes.ts from Trailforks trail polylines (public
// encodedpath on each trail page) plus EU-DEM 25 m elevations from OpenTopoData.
// Usage: node scripts/fetch-trail-routes.mjs <polylines.json>
//   polylines.json: { "<trailforks-slug>": [[lat, lon], ...], ... }
import { readFileSync, writeFileSync } from "node:fs";

const input = JSON.parse(readFileSync(process.argv[2], "utf8"));
const routes = {
  mundial: ["mundial-835186"],
  "free-ride": ["freeride-8627"],
  // Secret Spot is three consecutive Trailforks segments ending at the rider's
  // marked finish gate; Bonus Spot is the optional upper start.
  "secret-spot": ["secret-spot-234073", "secret-spot-838107", "secret-spot-838108"],
  // Optional upper drop-in timed as "sector 0" when a run starts there.
  "bonus-spot": ["bonus-spot"],
};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function elevations(points) {
  const out = [];
  for (let i = 0; i < points.length; i += 100) {
    const chunk = points.slice(i, i + 100);
    const res = await fetch(
      `https://api.opentopodata.org/v1/eudem25m?locations=${chunk.map((p) => p.join(",")).join("|")}`,
    );
    const body = await res.json();
    if (body.status !== "OK") throw new Error(JSON.stringify(body));
    out.push(...body.results.map((r) => Math.round(r.elevation)));
    await sleep(1100);
  }
  return out;
}
let source = `// Generated by scripts/fetch-trail-routes.mjs. Do not edit by hand.
// Geometry: Trailforks (Santa Marta, Braga). Elevation: EU-DEM 25 m.
export type RouteVertex = [lat: number, lon: number, ele: number];

`;
const parts = {};
for (const [id, slugs] of Object.entries(routes)) {
  const segments = [];
  for (const slug of slugs) {
    const pts = input[slug];
    const ele = await elevations(pts);
    segments.push(pts.map(([lat, lon], i) => [lat, lon, ele[i]]));
  }
  parts[id] = segments;
}
source += `export const TRAIL_ROUTES = {\n`;
for (const [id, segments] of Object.entries(parts))
  source += `  "${id}": [\n${segments.map((s) => `    [\n${s.map((p) => `      [${p.join(", ")}],`).join("\n")}\n    ],`).join("\n")}\n  ],\n`;
source += `} satisfies Record<string, RouteVertex[][]>;\n`;
writeFileSync(new URL("../src/lib/trailRoutes.ts", import.meta.url), source);
console.log(Object.fromEntries(Object.entries(parts).map(([k, s]) => [k, s.map((x) => `${x.length}pts ${x[0][2]}->${x.at(-1)[2]}m`)])));
